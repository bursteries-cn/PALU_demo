def run_analysis(
    result_root: Path,
    config: dict[str, Any],
    output_dir: Path,
    repo_root: Path,
) -> dict[str, Any]:
    _clean_owned_outputs(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    tables_dir = output_dir / "tables"
    figures_dir = output_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    all_records, warnings = collect_records(result_root)
    filtered = filter_records(all_records, config)
    cohort_records, protocol_excluded, protocol_cohorts = select_protocol_cohort(
        filtered, config
    )
    if protocol_excluded:
        warnings.append(
            f"excluded {len(protocol_excluded)} rows outside the largest protocol cohort; "
            "see tables/protocol_cohorts.csv"
        )
    selected = select_checkpoints(cohort_records, config)
    if filtered and not selected:
        checkpoint = config.get("checkpoint", {})
        epochs = sorted(
            {row.get("epoch") for row in cohort_records if row.get("epoch") is not None}
        )
        warnings.append(
            f"no rows matched checkpoint policy {checkpoint}; available epochs: "
            + ", ".join(str(value) for value in epochs)
        )

    observed = aggregate_configurations(selected)
    baselines, baseline_warnings = load_baselines(str(repo_root), config)
    warnings.extend(baseline_warnings)
    em_target = resolve_em_target(config, baselines)
    if em_target is None:
        warnings.append(
            "Retain exact_memorization baseline is unavailable; lower EM is treated as better when EM participates"
        )
    observed = rank_observed(observed, config, em_target)
    audit = coverage_audit(observed, config)
    factor_summary, factor_recommendations = build_factor_value_summary(
        observed, config
    )
    ledger = build_experiment_ledger(observed, config, cohort_records)
    next_experiments = recommend_neighbor_experiments(observed, ledger, config)

    preferred = [
        "status",
        *FACTORS,
        "epoch",
        *METRICS,
        "observed_score",
        "score_metrics_used",
        "score_metrics_expected",
        "n_runs",
        "pareto_observed",
    ]
    write_csv(tables_dir / "all_filtered_checkpoints.csv", cohort_records, preferred)
    write_csv(tables_dir / "selected_checkpoint_rows.csv", selected, preferred)
    write_csv(tables_dir / "observed_configurations.csv", observed, preferred)
    write_csv(tables_dir / "parameter_value_summary.csv", factor_summary)
    write_csv(
        tables_dir / "recommended_next_experiments.csv", next_experiments, preferred
    )
    write_csv(tables_dir / "experiment_ledger.csv", ledger, preferred)
    write_csv(
        tables_dir / "missing_combinations.csv",
        [row for row in ledger if row.get("status") == "missing"],
        preferred,
    )
    write_csv(
        tables_dir / "outside_search_space.csv", audit["outside_search_space"], preferred
    )
    write_csv(
        tables_dir / "protocol_cohorts.csv",
        protocol_cohorts,
        [*PROTOCOL_FIELDS, "n_rows"],
    )
    write_csv(
        tables_dir / "excluded_protocol_rows.csv", protocol_excluded, preferred
    )
    write_json(output_dir / "coverage_audit.json", audit)

    provenance = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "module_version": __version__,
        "python": platform.python_version(),
        "result_root": str(result_root.resolve()),
        "repo_root": str(repo_root.resolve()),
        "config": config,
        "baselines": baselines,
        "exact_memorization_target": em_target,
        "counts": {
            "all_records": len(all_records),
            "filtered_records": len(filtered),
            "protocol_cohort_records": len(cohort_records),
            "selected_checkpoint_records": len(selected),
            "observed_configurations": len(observed),
            "recommended_next_experiments": len(next_experiments),
        },
        "warnings": warnings,
    }
    write_json(output_dir / "provenance.json", provenance)

    guidance_paths = plot_parameter_guidance(
        factor_summary, figures_dir / "parameter_guidance", config
    )
    guidance_image = None
    for raw_path in guidance_paths:
        path = Path(raw_path)
        if path.suffix.lower() == ".png":
            guidance_image = path.relative_to(output_dir).as_posix()
            break
    build_html_report(
        output_dir / "report.html",
        observed,
        ledger,
        factor_summary,
        factor_recommendations,
        next_experiments,
        audit,
        baselines,
        em_target,
        guidance_image,
        warnings,
        config,
        provenance,
    )
    manifest = {
        "report": str((output_dir / "report.html").resolve()),
        "provenance": str((output_dir / "provenance.json").resolve()),
        "tables": str(tables_dir.resolve()),
        "figures": str(figures_dir.resolve()),
        "counts": provenance["counts"],
        "warnings": warnings,
    }
    write_json(output_dir / "manifest.json", manifest)
