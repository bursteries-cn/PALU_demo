def _clean_owned_outputs(output_dir: Path) -> None:
    """Remove only files generated by this module that can become stale on rerun."""
    explicit = [
        output_dir / "model_diagnostics.json",
        output_dir / "tables" / "adjusted_main_effects.csv",
        output_dir / "tables" / "interaction_strengths.csv",
        output_dir / "tables" / "observed_pareto.csv",
        output_dir / "tables" / "predicted_candidates.csv",
    ]
    for path in explicit:
        path.unlink(missing_ok=True)
    figure_dir = output_dir / "figures"
    owned_prefixes = (
        "coverage",
        "model_diagnostics",
        "observed_parallel_coordinates",
        "observed_tradeoffs",
        "epoch_trajectories",
        "main_effects_",
        "interactions_",
        "parameter_guidance",
    )
    if figure_dir.is_dir():
        for path in figure_dir.iterdir():
            if path.is_file() and path.name.startswith(owned_prefixes):
                path.unlink()


def _serializable(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _serializable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_serializable(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, (np.floating, float)):
        number = float(value)
        return number if math.isfinite(number) else None
    return value


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(_serializable(value), ensure_ascii=False, indent=2), encoding="utf-8"
    )


def _csv_cell(value: Any) -> Any:
    if value is None:
        return ""
    if isinstance(value, (dict, list, tuple, set)):
        return json.dumps(_serializable(value), ensure_ascii=False, sort_keys=True)
    return value


def write_csv(
    path: Path, rows: Iterable[dict[str, Any]], preferred: Iterable[str] = ()
) -> None:
    rows = list(rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    keys = {key for row in rows for key in row}
    fields = [key for key in preferred if key in keys]
    fields.extend(sorted(keys - set(fields)))
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        if not fields:
            handle.write("")
            return
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: _csv_cell(row.get(field)) for field in fields})


def _fmt(value: Any, digits: int = 4) -> str:
    if value is None:
        return "—"
    try:
        number = float(value)
    except (TypeError, ValueError):
        return html.escape(str(value))
    return f"{number:.{digits}g}"


def _warning_list(warnings: list[str]) -> str:
    if not warnings:
        return '<p class="ok">没有发现数据读取或实验协议警告。</p>'
    return "<ul>" + "".join(f"<li>{html.escape(item)}</li>" for item in warnings) + "</ul>"


def _metric_cards(audit: dict[str, Any]) -> str:
    return "".join(
        f'<div class="metricCard"><b>{audit["metric_complete"].get(metric, 0)}</b>'
        f'<span>{html.escape(METRIC_LABELS[metric])}</span></div>'
        for metric in METRICS
    )


def _promising_table(recommendations: list[dict[str, Any]]) -> str:
    rows = []
    for item in recommendations:
        values = item.get("promising_values", [])
        value_text = ", ".join(
            display_factor_value(item["factor"], value) for value in values
        ) or "尚无可评分结果"
        rows.append(
            "<tr>"
            f'<td><strong>{html.escape(FACTOR_LABELS[item["factor"]])}</strong></td>'
            f"<td>{html.escape(value_text)}</td>"
            f'<td>{_fmt(item.get("best_score_median"), 3)}</td>'
            f'<td>{item.get("support_configurations", 0)}</td>'
            f'<td>{html.escape(str(item.get("evidence", "—")))}</td>'
            "</tr>"
        )
    return "".join(rows)


def _factor_summary_table(summary: list[dict[str, Any]]) -> str:
    rows = []
    for item in summary:
        status = "已实验" if item["status"] == "tested" else "未实验"
        rows.append(
            f'<tr class="{item["status"]}">'
            f'<td>{html.escape(FACTOR_LABELS[item["factor"]])}</td>'
            f'<td>{html.escape(display_factor_value(item["factor"], item["value"]))}</td>'
            f'<td><span class="pill {item["status"]}">{status}</span></td>'
            f'<td>{item["n_configurations"]}</td>'
            f'<td>{item["n_runs"]}</td>'
            f'<td>{_fmt(item.get("score_median"), 3)}</td>'
            f'<td>{_fmt(item.get("model_utility_median"), 5)}</td>'
            f'<td>{_fmt(item.get("forget_quality_median"), 5)}</td>'
            f'<td>{_fmt(item.get("forget_Q_A_gibberish_median"), 5)}</td>'
            f'<td>{_fmt(item.get("exact_memorization_median"), 5)}</td>'
            f'<td>{html.escape(str(item.get("evidence", "—")))}</td>'
            "</tr>"
        )
    return "".join(rows)


def _top_observed_table(observed: list[dict[str, Any]], limit: int = 5) -> str:
    rows = [row for row in observed if row.get("observed_score") is not None][:limit]
    if not rows:
        return '<tr><td colspan="12">当前没有足够的指标值用于相对评分。</td></tr>'
    return "".join(
        "<tr>"
        f"<td>{index}</td>"
        + "".join(f"<td>{_fmt(row.get(factor), 5)}</td>" for factor in FACTORS)
        + f'<td><strong>{_fmt(row.get("observed_score"), 3)}</strong></td>'
        + f'<td>{row.get("score_metrics_used", 0)}/{row.get("score_metrics_expected", 0)}</td>'
        + "".join(f"<td>{_fmt(row.get(metric), 5)}</td>" for metric in METRICS)
        + "</tr>"
        for index, row in enumerate(rows, start=1)
    )


def _next_experiment_table(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return (
            '<tr><td colspan="8">没有生成邻域建议：需要至少一个具有可评分指标的已实验配置。</td></tr>'
        )
    return "".join(
        "<tr>"
        f'<td><strong>{row["priority"]}</strong></td>'
        + "".join(f"<td>{_fmt(row.get(factor), 5)}</td>" for factor in FACTORS)
        + f'<td>{html.escape(str(row.get("primary_change", "—")))}</td>'
        + f'<td>{row.get("neighbor_support", 1)}</td>'
        + f'<td>{_fmt(row.get("best_source_score"), 3)}</td>'
        + "</tr>"
        for row in rows
    )


